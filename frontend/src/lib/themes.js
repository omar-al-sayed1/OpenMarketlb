export function getThemeConfig(themeKey, shopAccentColor) {
  const config = themes[themeKey] || themes.classic;
  
  // Add computed UI styles based on theme
  const uiStyles = {
    // Filter sidebar
    filterBg: config.darkMode ? 'bg-zinc-900 border-zinc-800' : 'bg-white border-slate-100',
    filterIconBg: config.darkMode ? 'bg-zinc-800' : `bg-gradient-to-br ${config.accentFrom} ${config.accentTo}`,
    filterIconColor: 'text-white',
    filterLabel: config.darkMode ? 'text-zinc-400' : 'text-slate-400',
    filterTitle: config.darkMode ? 'text-zinc-200' : 'text-slate-900',
    // Search bar
    searchBg: config.darkMode ? 'bg-zinc-900 border-zinc-700 text-zinc-200 placeholder:text-zinc-500' : 'bg-white border-slate-200 text-slate-900',
    searchIconColor: config.darkMode ? 'text-zinc-500' : 'text-slate-400',
    // Sort select
    sortBorder: config.darkMode ? 'border-zinc-700 bg-zinc-900 text-zinc-200' : 'border-slate-200',
    // Product count text
    countText: config.darkMode ? 'text-zinc-400' : 'text-slate-600',
    countBold: config.darkMode ? 'text-zinc-200' : 'text-slate-800',
    // Price slider
    sliderBg: config.darkMode ? 'bg-zinc-800 border-zinc-700' : `bg-gradient-to-r ${config.accentFrom.replace('from-', 'from-')}/5 ${config.accentTo.replace('to-', 'to-')}/10 border border-${config.accentFrom.includes('violet') ? 'violet' : config.accentFrom.includes('rose') ? 'rose' : config.accentFrom.includes('amber') ? 'amber' : config.accentFrom.includes('emerald') ? 'emerald' : config.accentFrom.includes('sky') ? 'sky' : config.accentFrom.includes('blue') ? 'blue' : config.accentFrom.includes('red') ? 'red' : config.accentFrom.includes('pink') ? 'pink' : config.accentFrom.includes('purple') ? 'purple' : 'violet'}-100`,
    sliderText: config.darkMode ? 'text-zinc-300' : undefined,
    // Empty state
    emptyBg: config.darkMode ? 'bg-zinc-900' : 'bg-white',
    emptyText: config.darkMode ? 'text-zinc-400' : 'text-slate-700',
    emptySubtext: config.darkMode ? 'text-zinc-500' : 'text-slate-500',
    // Clear filters button
    clearBtnClass: config.darkMode ? 'border-zinc-700 hover:bg-red-950 hover:text-red-400 hover:border-red-800' : 'border-slate-200 hover:bg-red-50 hover:text-red-600 hover:border-red-200',
    // Active filter style
    activeFilterBg: config.darkMode ? `bg-gradient-to-r ${config.accentFrom} ${config.accentTo} text-white` : undefined,
  };

  const result = { ...config, ...uiStyles };
  if (shopAccentColor) {
    result.customAccent = shopAccentColor;
  }
  return result;
}

export default themes;
